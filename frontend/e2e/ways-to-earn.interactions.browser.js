// Run after ways-to-earn.browser.js has installed its isolated API fixtures.
async (page) => {
  page.setDefaultTimeout(6000);
  const base=new URL(page.url()).origin, checks=[];
  const fixture=patch=>page.evaluate(async p=>(await fetch('/api/v1/admin/loyalty/__fixture',p?{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(p)}:undefined)).json(),patch);
  const original=structuredClone((await fixture()).answer);
  const ok=(condition,name)=>{if(!condition)throw Error(name);checks.push(name)};
  const go=async search=>{await page.goto(base+'/loyalty/options'+search);await page.locator('.l-earn-page').waitFor()};
  const writes=async()=> (await fixture()).requests.filter(r=>r.method==='PUT');
  const rate=()=>page.locator('[data-field="points_per_currency"] input');
  const bonus=()=>page.locator('.l-earn-bonus-editor');
  const saveBonus=()=>bonus().getByRole('button',{name:'Save bonus',exact:true});
  const rules=()=>page.locator('.l-earn-shared');
  const saved=async form=>{await form.getByRole('status').waitFor()};
  const payload=async expected=>{const all=await writes();ok(JSON.stringify(all.at(-1).payload.options)===JSON.stringify(expected),'partial payload '+JSON.stringify(expected))};
  try {
    await go('');ok(await page.locator('[data-way]').count()===6,'six existing earning methods');
    await page.getByLabel('Search earning rules',{exact:true}).fill('stamp');
    await page.locator('[data-way="earn_rate"]').waitFor({state:'hidden'});
    ok(await page.locator('[data-way]').count()===1&&page.url().includes('q=stamp'),'search filters and URL');
    await page.getByLabel('Search earning rules',{exact:true}).fill('missing');
    await page.getByText('No earning methods match these filters.').waitFor();checks.push('filtered empty state');
    await page.getByRole('button',{name:'Clear filters'}).click();
    await page.locator('[data-way="earn_rate"]').waitFor();
    await page.getByRole('combobox',{name:'Status',exact:true}).selectOption('off');
    await page.locator('[data-way="earn_rate"]').waitFor({state:'hidden'});
    ok(await page.locator('[data-way]').count()===2,'status filter follows switches');
    await page.getByRole('combobox',{name:'Status',exact:true}).selectOption('all');
    await page.locator('[data-way="check_in"]').waitFor();
    await page.locator('[data-way="check_in"] .l-earn-row-content').click();
    ok(page.url().includes('selected=check_in'),'row selection is bookmarkable');
    await page.getByRole('button',{name:'+ Add earning rule',exact:true}).click();
    ok(await page.getByRole('dialog').getByRole('button',{name:/Configure /}).count()===6,'chooser uses all existing earning methods');
    await page.getByRole('button',{name:'Configure Purchase points',exact:true}).click();
    await rate().waitFor();ok(await rate().inputValue()==='5','purchase editor uses API rate');
    await page.getByRole('button',{name:'10 points',exact:true}).click();
    ok(await rate().inputValue()==='10'&&await page.locator('.l-earn-big').textContent()==='500 points','quick set updates member preview');
    await page.getByLabel('Eligible purchase amount',{exact:true}).fill('12.99');
    ok(await page.locator('.l-earn-big').textContent()==='129 points','example floors whole points');
    await page.getByLabel('Eligible purchase amount',{exact:true}).fill('-1');
    await page.getByText('Enter a valid rate and a non-negative purchase amount to see the example.').waitFor();checks.push('invalid example has no invented total');
    await page.getByLabel('Eligible purchase amount',{exact:true}).fill('50');
    await rate().fill('');await page.getByRole('button',{name:'Save changes',exact:true}).click();
    ok(await rate().getAttribute('aria-invalid')==='true'&&(await writes()).length===0,'blank rate validates and cannot write');
    await page.getByRole('link',{name:'Help & guide',exact:true}).click();
    await page.getByRole('dialog',{name:'Discard unsaved changes?'}).waitFor();
    await page.getByRole('button',{name:'Keep editing',exact:true}).click();
    ok(await rate().inputValue()==='','invalid draft is protected on navigation');
    await rate().fill('1001');await page.getByRole('button',{name:'Save changes',exact:true}).click();
    ok(await rate().getAttribute('aria-invalid')==='true'&&(await writes()).length===0,'server maximum validates before PUT');
    await rate().fill('2.25');
    await page.getByRole('button',{name:/Increase Points for each/}).click();
    ok(await rate().inputValue()==='2.26','decimal stepper uses 0.01');
    await page.getByRole('button',{name:/Decrease Points for each/}).click();
    await page.getByRole('button',{name:'Show',exact:false}).click();
    await page.getByText(/Overlapping boosts use the highest matching boost/).waitFor();checks.push('calculation disclosure works');
    await fixture({writeFail:true});await page.getByRole('button',{name:'Save changes',exact:true}).click();
    await page.locator('.l-earn-settings').getByRole('alert').waitFor();
    ok(await rate().inputValue()==='2.25','failed save retains draft');
    await fixture({writeFail:false,fieldFail:true});await page.getByRole('button',{name:'Save changes',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('[data-field="points_per_currency"] input')?.getAttribute('aria-invalid')==='true');checks.push('server field refusal shown');
    await fixture({fieldFail:false,slow:true});await page.getByRole('button',{name:'Save changes',exact:true}).click();
    ok(await rate().isDisabled(),'pending save locks inputs');
    await page.getByRole('link',{name:'Help & guide',exact:true}).click();
    ok(page.url().includes('way=earn_rate'),'pending write blocks internal navigation');
    await saved(page.locator('.l-earn-settings'));await payload({points_per_currency:2.25});
    await fixture({slow:false});
    await page.getByRole('button',{name:'Cancel',exact:true}).click();
    await page.locator('[data-way="earn_rate"]').waitFor();
    ok((await page.locator('[data-way="earn_rate"]').innerText()).includes('2.25 points'),'saved rate refreshes list');
    await go('?tab=bonus');
    await bonus().getByRole('button',{name:'500',exact:true}).click();
    await rules().getByRole('combobox',{name:'Points expiry',exact:true}).selectOption('custom');
    await rules().getByLabel('Expiry in months',{exact:true}).fill('7');
    await rules().getByRole('button',{name:'Save rules',exact:true}).click();await saved(rules());await payload({points_expiry_months:7});
    ok(await bonus().getByLabel('Bonus points',{exact:true}).inputValue()==='500'&&await saveBonus().isEnabled(),'bonus draft survives separate rules save');
    await rules().getByRole('combobox',{name:'Qualify for levels using',exact:true}).selectOption('visits');
    await saveBonus().click();await saved(bonus());await payload({welcome_bonus_points:500});
    ok(await rules().getByRole('combobox',{name:'Qualify for levels using',exact:true}).inputValue()==='visits'&&await rules().getByRole('button',{name:'Save rules',exact:true}).isEnabled(),'rules draft survives bonus save');
    await rules().getByRole('button',{name:'Save rules',exact:true}).click();await saved(rules());await payload({tier_progress_by:'visits'});
    await rules().getByRole('combobox',{name:'Points expiry',exact:true}).selectOption('0');
    await rules().getByRole('button',{name:'Save rules',exact:true}).click();await saved(rules());await payload({points_expiry_months:0});
    await bonus().getByRole('combobox',{name:'Status',exact:true}).selectOption('off');await saveBonus().click();await saved(bonus());await payload({welcome_bonus_points:0});
    ok(await bonus().getByLabel('Bonus points',{exact:true}).isDisabled(),'disabled bonus keeps zero-off semantics');
    await bonus().getByRole('combobox',{name:'Status',exact:true}).selectOption('active');
    await bonus().getByRole('button',{name:'Cancel changes',exact:true}).click();
    ok(await bonus().getByRole('combobox',{name:'Status',exact:true}).inputValue()==='off','cancel restores server state');
    await page.locator('[data-way="birthday_bonus"] .l-earn-open').click();
    await bonus().getByRole('button',{name:'100',exact:true}).click();
    await rules().getByRole('combobox',{name:'Qualify for levels using',exact:true}).selectOption('spend');
    await page.locator('[data-way="referrals"] .l-earn-open').click();
    await page.getByRole('dialog',{name:'Discard unsaved changes?'}).waitFor();
    await page.keyboard.press('Escape');
    ok(await bonus().getByLabel('Bonus points',{exact:true}).inputValue()==='100','Escape keeps bonus draft');
    await page.locator('[data-way="referrals"] .l-earn-open').click();
    await page.getByRole('button',{name:'Discard changes',exact:true}).click();
    await bonus().getByRole('heading',{name:'Referrals',exact:true}).waitFor();
    ok(await rules().getByRole('combobox',{name:'Qualify for levels using',exact:true}).inputValue()==='visits','discard resets the still-mounted shared rules draft');
    await bonus().getByRole('combobox',{name:'Status',exact:true}).selectOption('active');
    await bonus().locator('[data-field="referral_reward_on"] select').selectOption('signup');
    await saveBonus().click();await saved(bonus());await payload({referral_enabled:true,referral_reward_on:'signup'});
    await go('?way=stamp_card');
    await page.locator('[data-field="stamp_reward_kind"] select').selectOption('reward');
    await page.locator('[data-field="stamp_reward_id"] select').selectOption('9');
    ok(await page.locator('[data-field="stamp_reward_points"]').count()===0,'stamp reward fields follow server conditions');
    await page.getByRole('button',{name:'Save changes',exact:true}).click();await saved(page.locator('.l-earn-settings'));await payload({stamp_reward_kind:'reward',stamp_reward_id:9});
    for(const [way,key,on] of [['points_on_spend','points_on_bookings',false],['desk_earn','desk_earn_enabled',true],['cashback','cashback_enabled',true]]) {
      await go('?way='+way);await page.getByRole('combobox',{name:'Status',exact:true}).selectOption(on?'active':'off');
      await page.getByRole('button',{name:'Save changes',exact:true}).click();await saved(page.locator('.l-earn-settings'));await payload({[key]:on});
    }
    await go('?way=check_in');await page.locator('[data-field="checkin_points"] input').fill('42');
    await page.getByRole('button',{name:'Save changes',exact:true}).click();await saved(page.locator('.l-earn-settings'));await payload({checkin_points:42});
    await go('?way=welcome_bonus');ok(await page.locator('.l-rd-subnav-active').textContent()==='Bonuses','legacy bonus bookmark selects matching shell tab');
    const state=await fixture();ok(state.errors.length===0,'zero browser runtime errors');
    ok(state.requests.filter(r=>r.method==='PUT').every(r=>r.path==='options'&&r.query==='?brand_id=all'),'all writes use existing tenant-scoped options endpoint');
    await fixture({answer:original,requests:[]});
    return {passed:checks.length,checks};
  } catch(error) {
    // Return the failing assertion even if the browser has a pending native leave prompt.
    return {passed:checks.length,checks,error:String(error),url:page.url()};
  }
}
