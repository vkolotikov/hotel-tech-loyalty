import { expect, it } from 'vitest'
import { DraftRegistry } from './registry'
it('adopts refreshed authority only for clean entries without changing their ownership ticket', () => {
  const drafts = new DraftRegistry(), key = 'account|3::planning-zone'
  drafts.read(key, () => 'Europe/Riga')
  const ticket = drafts.ticket(key)
  drafts.adoptIfClean(key, 'Europe/Paris')
  expect(drafts.read(key, () => '')).toBe('Europe/Paris')
  expect(drafts.owns(key, ticket)).toBe(true)
  expect(drafts.dirty()).toBe(false)
  drafts.write(key, 'Europe/Berlin')
  drafts.adoptIfClean(key, 'Europe/Riga')
  expect(drafts.read(key, () => '')).toBe('Europe/Berlin')
  expect(drafts.dirty()).toBe(true)
  drafts.write(key, 'Europe/Paris')
  expect(drafts.dirty()).toBe(false)
  drafts.adoptIfClean(key, 'Europe/Riga')
  expect(drafts.read(key, () => '')).toBe('Europe/Riga')
})
it('retains brand edits without crossing account or brand, and acknowledges only the submitted snapshot', () => {
  const drafts = new DraftRegistry()
  drafts.read('account|3::summary', () => 'old')
  drafts.write('account|3::summary', 'submitted')
  drafts.write('account|3::summary', 'later')
  drafts.acknowledge('account|3::summary', 'submitted')
  expect(drafts.dirty('account|3')).toBe(true)
  expect(drafts.dirtySession('other')).toBe(false)
  expect(drafts.read('account|3::summary', () => 'other')).toBe('later')
  expect(drafts.read('account|4::summary', () => 'brand B')).toBe('brand B')
  expect(drafts.read('other|3::summary', () => 'other account')).toBe('other account')
  drafts.clear('account|3')
  expect(drafts.dirty()).toBe(false)
  drafts.read('account|3::bio', () => null)
  drafts.write('account|3::bio', { title: 'unsaved' })
  expect(drafts.dirty('account|3')).toBe(true)
  const oldOpening = drafts.ticket('account|3::bio')
  drafts.clear('account|3')
  drafts.read('account|3::bio', () => ({ title: 'new opening' }))
  expect(drafts.owns('account|3::bio', oldOpening)).toBe(false)
})
