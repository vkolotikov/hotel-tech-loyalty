/** Review regressions exercise the production controller, composer and Locations section. */
export async function fixChecks({ page, open, hook, receipt, evidence }) {
  const scenario = async (name, run) => { try { await run() } catch (error) { evidence.checks.push({ name, passed: false, detail: String(error) }) } }
  const fullPost = async () => { await open(); await page.getByRole('button', { name: 'Audit saved post', exact: true }).click(); await page.getByRole('link', { name: 'Full editor' }).click(); await hook().waitFor() }
  for (const transition of [false, true]) await scenario(`Delayed quality read after Save (${transition ? 'panel/full' : 'full'})`, async () => {
    await fullPost()
    await page.evaluate(() => { window.__auditData.advanceRevision = true })
    await page.getByRole('button', { name: 'Check quality', exact: true }).click()
    await page.evaluate(() => window.__finish('POST'))
    await page.evaluate(() => { window.__auditData.holdPostRead = true; window.__auditData.posts[301].quality = { overall: 8 }; window.__auditData.work = { ...window.__auditData.work, status: 'succeeded', can_cancel: false } })
    await page.waitForFunction(() => window.__auditData.pending.some(p => p.method === 'GET'))
    if (transition) await page.getByRole('link', { name: 'Open in panel' }).click()
    await hook().fill('Later successfully saved human text')
    await page.getByRole('button', { name: 'Save draft', exact: true }).click()
    await page.evaluate(() => window.__finish('PUT'))
    await page.waitForFunction(() => !window.__editor.saving)
    if (transition) await page.getByRole('link', { name: 'Full editor' }).click()
    await page.evaluate(() => window.__finish('GET'))
    await page.waitForTimeout(120)
    await receipt(`Delayed quality read cannot regress a newer saved revision (${transition ? 'panel/full' : 'full'})`, await hook().inputValue() === 'Later successfully saved human text' && await page.evaluate(() => window.__editor.post.updated_at === window.__auditData.posts[301].updated_at && window.__cachedPost(301).updated_at === window.__auditData.posts[301].updated_at))
    await page.getByRole('button', { name: 'Check quality', exact: true }).click()
    await page.evaluate(() => window.__finish('POST'))
    await page.evaluate(() => { window.__auditData.posts[301].quality = { overall: 9 }; window.__auditData.work = { ...window.__auditData.work, status: 'succeeded', can_cancel: false } })
    await page.getByText('Score: 9 of 10', { exact: true }).waitFor()
    await receipt('Same-revision quality metadata remains adoptable', await hook().inputValue() === 'Later successfully saved human text')
  })
  await scenario('Full composer shared-action route lifecycle', async () => {
    await fullPost()
    await page.getByRole('button', { name: 'More actions', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Duplicate', exact: true }).click()
    await page.evaluate(() => { window.__auditData.posts[999] = { group: { id: 999, adapting: [], kept_original: [], kept_reason: null, posts: [{ id: 999, platform: 'linkedin', status: 'draft', scheduled_date: null }, { id: 401, platform: 'instagram', status: 'draft', scheduled_date: null }] } }; window.__finish('POST') })
    await page.waitForFunction(() => window.__panel.target?.id === 999)
    await page.waitForTimeout(50)
    await receipt('Actual Duplicate synchronizes the full route', await page.locator('#route').textContent() === '/content/write/999')
    await page.getByRole('button', { name: 'Versions & repeat', exact: true }).click()
    await page.getByRole('button', { name: /^Instagram/ }).click()
    await page.waitForFunction(() => document.querySelector('#route').textContent === '/content/write/401')
    await receipt('Actual version selection synchronizes route and target', await page.evaluate(() => window.__editor.post?.id === 401))
    await page.getByRole('button', { name: 'Audit back', exact: true }).click()
    await page.waitForFunction(() => window.__editor?.post?.id === 999)
    await receipt('Back restores the previous post route and target', await page.locator('#route').textContent() === '/content/write/999')
    await page.getByRole('button', { name: 'Audit new post', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('#route').textContent === '/content/write/new')
    const seq = await page.evaluate(() => window.__panel.target.seq)
    await receipt('Shared New opens the new route without a second opening', await page.evaluate(seq => window.__editor.target.seq === seq, seq))
    await page.getByRole('button', { name: 'Audit back', exact: true }).click()
    await page.waitForFunction(() => window.__editor?.post?.id === 999)
    await page.getByRole('button', { name: 'More actions', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Delete', exact: true }).click()
    await page.getByRole('button', { name: 'Delete post', exact: true }).click()
    await page.evaluate(() => window.__finish('DELETE'))
    await page.waitForFunction(() => window.__panel.target === null)
    await page.waitForTimeout(50)
    await receipt('Actual Delete leaves the closed full editor for Posts', await page.locator('#route').textContent() === '/content/posts')
  })
  await scenario('Retained location identity during reads and brand switch', async () => {
    await open()
    const locations = async () => { await page.getByRole('link', { name: 'Real Brand navigation' }).click(); await page.getByRole('button', { name: 'Locations', exact: true }).click() }
    await locations();await page.getByRole('button', { name: 'Edit', exact: true }).click()
    await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Retained venue seven')
    await page.getByRole('link', { name: 'Plan navigation', exact: true }).click()
    await page.evaluate(() => { window.__dropLocations(); window.__auditData.holdLocations = true })
    await locations()
    await page.waitForFunction(() => window.__auditData.pending.some(p => p.url.includes('/locations')))
    await receipt('Unresolved existing location never renders a create form', await page.getByRole('textbox', { name: 'Name', exact: true }).count() === 0 && await page.getByRole('button', { name: 'Save', exact: true }).count() === 0)
    await page.evaluate(() => { window.__auditData.holdLocations = false; window.__finish('GET') })
    await receipt('Delayed location read restores its retained draft', await page.getByRole('textbox', { name: 'Name', exact: true }).inputValue() === 'Retained venue seven')
    await page.getByRole('link', { name: 'Plan navigation', exact: true }).click()
    await page.evaluate(() => { window.__dropLocations(); window.__auditData.failLocations = true })
    await locations();await page.getByRole('button', { name: 'Try again', exact: true }).waitFor()
    await receipt('Failed location read offers retry without a create Save', await page.getByRole('button', { name: 'Save', exact: true }).count() === 0)
    await page.evaluate(() => { window.__auditData.failLocations = false })
    await page.getByRole('button', { name: 'Try again', exact: true }).click()
    await page.getByRole('textbox', { name: 'Name', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Audit switch brand', exact: true }).click()
    await page.getByRole('button', { name: 'Audit switch brand', exact: true }).click()
    await page.getByRole('textbox', { name: 'Name', exact: true }).waitFor()
    await receipt('Returning after brand switch retains existing location draft', await page.getByRole('textbox', { name: 'Name', exact: true }).inputValue() === 'Retained venue seven')
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    await page.waitForFunction(() => window.__auditData.pending.some(p => p.method !== 'GET'))
    await receipt('Retained existing location saves only through its PUT identity', await page.evaluate(() => window.__auditData.pending.some(p => p.method === 'PUT' && p.url.includes('/locations/7?')) && !window.__auditData.requests.some(p => p.method === 'POST' && p.url.includes('/locations'))))
    await page.evaluate(() => window.__finish('PUT'))
    await page.getByRole('button', { name: 'Add location', exact: true }).click()
    await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Explicit new venue')
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    await page.waitForFunction(() => window.__auditData.pending.some(p => p.method === 'POST'))
    await receipt('Only an explicit Add location target creates a location', await page.evaluate(() => window.__auditData.pending.some(p => p.method === 'POST' && p.url.includes('/locations?') && p.body.name === 'Explicit new venue')))
  })
}
