/** Additional Task6 behavior checks; the original 41 remain untouched. */
export async function launchChecks({ page, open, hook, receipt }) {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await open()
  await page.getByRole('link', { name: 'Audit full composer' }).click()
  await hook().fill('Full composer words')
  const seq = await page.evaluate(() => window.__panel.target.seq)
  await page.getByRole('link', { name: 'Open in panel' }).click()
  await receipt('Full composer to panel keeps one draft and opening', await hook().inputValue() === 'Full composer words' && await page.evaluate(() => window.__panel.target.seq) === seq)
  await page.getByRole('link', { name: 'Full editor' }).click()
  await hook().fill('Submitted full words')
  await page.getByRole('button', { name: 'Create post', exact: true }).click()
  await hook().fill('Full words typed after Create')
  await page.evaluate(() => window.__finish())
  await page.waitForFunction(() => document.querySelector('#route')?.textContent === '/content/write/101')
  await receipt('Full Create replaces URL without replacing draft or opening', await hook().inputValue() === 'Full words typed after Create' && await page.evaluate(() => window.__panel.target.seq) === seq)
  await page.getByRole('link', { name: 'Open in panel' }).click()
  await receipt('Create pending typing is shared back to panel', await hook().inputValue() === 'Full words typed after Create')

  await open()
  await page.getByRole('button', { name: 'Audit saved post', exact: true }).click()
  await page.getByRole('link', { name: 'Full editor' }).click()
  await page.evaluate(() => { window.__auditData.failWorkStart = true })
  await page.getByRole('button', { name: 'Write the text', exact: true }).click()
  await page.getByRole('button', { name: 'Reconnect', exact: true }).waitFor()
  await page.evaluate(() => { window.__auditData.failWorkStart = false })
  await page.getByRole('button', { name: 'Reconnect', exact: true }).click()
  await page.waitForFunction(() => window.__auditData.pending.length === 1)
  const keys = await page.evaluate(() => window.__auditData.requests.filter(r => r.method === 'POST' && r.url.includes('/work')).map(r => r.body))
  await receipt('Ambiguous start reconnects with identical key and submitted input', keys.length === 2 && JSON.stringify(keys[0]) === JSON.stringify(keys[1]))
  await page.evaluate(() => window.__finish())
  await page.getByRole('button', { name: 'Cancel AI work' }).waitFor()
  await hook().fill('Typing during queued work')
  await page.getByRole('link', { name: 'Open in panel' }).click()
  await page.getByRole('button', { name: 'Cancel AI work' }).waitFor()
  await receipt('Queued work recovers in panel with later words', await hook().inputValue() === 'Typing during queued work')
  await page.evaluate(() => { window.__auditData.work = { ...window.__auditData.work, status: 'running', can_cancel: false } })
  await page.waitForFunction(() => !Array.from(document.querySelectorAll('button')).some(b => b.textContent === 'Cancel AI work'))
  await receipt('Cancellation follows server capability rather than status guess', true)
  await page.evaluate(() => { window.__auditData.posts[301] = { ...(window.__auditData.posts[301] || {}), id: 301, platform: 'linkedin', status: 'draft', hook: 'AI returned hook', hashtags: [], updated_at: '2026-11-13T06:00:01Z' }; window.__auditData.work = { ...window.__auditData.work, status: 'succeeded', result: { post_id: 301 } } })
  await page.waitForTimeout(1800)
  await receipt('Completed queued write does not overwrite later human typing', await hook().inputValue() === 'Typing during queued work')

  await page.getByRole('link', { name: 'Full editor' }).click()
  await page.getByRole('button', { name: 'Rewrite', exact: true }).click()
  await page.evaluate(() => window.__finish())
  await page.evaluate(() => { window.__auditData.work = { ...window.__auditData.work, status: 'succeeded', result: { variation: { id: 88, copy: 'Explicit proposed variation' } }, can_cancel: false } })
  await page.getByRole('button', { name: 'Use this text', exact: true }).waitFor()
  await receipt('Rewrite waits for explicit use and preserves existing typing', await hook().inputValue() === 'Typing during queued work')
  await page.getByRole('button', { name: 'Use this text', exact: true }).click()
  await receipt('Explicit rewrite use changes only draft copy', await page.getByLabel('Post text', { exact: true }).inputValue() === 'Explicit proposed variation')

  await open()
  await page.getByRole('button', { name: 'Audit saved post', exact: true }).click()
  await page.getByRole('link', { name: 'Full editor' }).click()
  await page.getByRole('button', { name: 'Visual brief', exact: true }).click()
  await page.evaluate(() => window.__finish())
  await page.evaluate(() => { window.__auditData.work = { ...window.__auditData.work, status: 'failed', error: 'ai_failed', can_cancel: false } })
  await page.getByRole('button', { name: 'Try again', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Try again', exact: true }).click()
  await page.waitForFunction(() => window.__auditData.pending.length === 1)
  const retryKeys = await page.evaluate(() => window.__auditData.requests.filter(r => r.method === 'POST' && r.url.includes('/work')).map(r => r.body.request_key))
  await receipt('Intentional retry uses a new request key after terminal failure', retryKeys.length === 2 && retryKeys[0] !== retryKeys[1])
  await page.evaluate(() => window.__finish())
  await page.getByRole('button', { name: 'Cancel AI work' }).click()
  await page.evaluate(() => window.__finish())
  await page.getByText('AI work cancelled. Earlier saved changes remain.', { exact: true }).waitFor()
  await receipt('Cancellation applies server terminal response', await page.getByText('AI work cancelled. Earlier saved changes remain.', { exact: true }).isVisible())

  for (const kind of ['snippets', 'templates']) {
    await open()
    await page.evaluate(kind => {
      window.__auditData[kind] = [1,2].map(id => ({ id, kind: 'text', name: `${kind} ${id}`, body: `Text ${id}`, main_copy: `Text ${id}`, platform: 'linkedin', hashtags: [] }))
      window.__refreshBrand()
    }, kind)
    await page.getByRole('link', { name: 'Real Brand navigation' }).click()
    await page.getByRole('button', { name: 'Reusable content', exact: true }).click()
    const section = page.locator(kind === 'snippets' ? 'section[aria-labelledby="content-snippets"]' : 'section[aria-labelledby="content-templates"]')
    await section.locator('li').filter({ hasText: `${kind} 1` }).getByRole('button', { name: 'Edit', exact: true }).click()
    const field = section.getByRole('textbox', { name: /^Text/ })
    await field.fill('Submitted A')
    await section.getByRole('button', { name: 'Save', exact: true }).click()
    await section.locator('li').filter({ hasText: `${kind} 2` }).getByRole('button', { name: 'Edit', exact: true }).click()
    await field.fill('Retained B words')
    await page.evaluate(() => window.__finish())
    await page.waitForTimeout(80)
    await receipt(`${kind} old A Save cannot close B or remove B typing`, await field.inputValue() === 'Retained B words')
    await page.getByRole('button', { name: 'Identity', exact: true }).click()
    await page.getByRole('button', { name: 'Audit back', exact: true }).click()
    await receipt(`${kind} URL Back restores section and retained B`, await field.inputValue() === 'Retained B words')
  }
}
