/** Feedback uses the same retained tab registry across full/panel and delayed responses. */
export async function collaborationChecks({ page, open, receipt }) {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await open()
  await page.evaluate(() => {
    window.__auditData.team = [{ id: 2, name: 'Explicit teammate', role: 'staff' }]
    window.__auditData.media = [{ id: 21, name: 'Review attachment.pdf', mime: 'application/pdf', url: '/local.pdf', size: 100, archived: false, usage_count: 1 }]
  })
  await page.getByRole('button', { name: 'Audit saved post', exact: true }).click()
  await page.getByRole('link', { name: 'Full editor' }).click()
  await page.evaluate(() => { window.__auditData.posts[301].media = window.__auditData.media })
  // Read the existing stored media through a fresh opening.
  await page.getByRole('link', { name: 'Open in panel' }).click()
  await page.locator('[data-panel]').getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'Audit saved post', exact: true }).click()
  await page.getByRole('link', { name: 'Full editor' }).click()
  const box = () => page.getByLabel('Write a comment', { exact: true })
  await box().fill('Retained explicit feedback')
  await page.getByLabel('Discuss an attachment', { exact: true }).selectOption('21')
  await page.getByLabel('Explicit teammate', { exact: true }).check()
  await page.getByRole('link', { name: 'Open in panel' }).click()
  await page.getByRole('tab', { name: /Activity/ }).click()
  await receipt('Comment text media and explicit mentions survive full to panel', await box().inputValue() === 'Retained explicit feedback' && await page.getByLabel('Discuss an attachment', { exact: true }).inputValue() === '21' && await page.getByLabel('Explicit teammate', { exact: true }).isChecked())
  await page.getByRole('link', { name: 'Full editor' }).click()
  await receipt('Panel to full retains feedback separately from main draft', await box().inputValue() === 'Retained explicit feedback' && await page.evaluate(() => window.__editor.dirty === false))
  await page.evaluate(() => { window.__auditData.failComment = true })
  await page.getByRole('button', { name: 'Comment', exact: true }).click()
  await page.getByText('The attachment or team selection changed. Choose again below; your comment is kept.').waitFor()
  await receipt('Failed attachment validation keeps text and offers correction', await box().inputValue() === 'Retained explicit feedback')
  await page.evaluate(() => { window.__auditData.failComment = false })
  await page.getByRole('button', { name: 'Comment', exact: true }).click()
  await receipt('Pending comment disables fields so later feedback cannot be cleared', await box().isDisabled() && await page.getByLabel('Discuss an attachment', { exact: true }).isDisabled() && await page.getByLabel('Explicit teammate', { exact: true }).isDisabled())
  await page.getByRole('link', { name: 'Open in panel' }).click()
  await page.getByRole('tab', { name: /Activity/ }).click()
  await receipt('Pending comment remains disabled after full to panel navigation', await box().isDisabled())
  await page.evaluate(() => window.__finish())
  await page.waitForFunction(() => document.querySelector('textarea[aria-describedby="content-timeline-hint"]')?.value === '')
  await receipt('Acknowledged comment renders asset context and selected teammate', await page.locator('[data-comment]').getByText('Attachment: Review attachment.pdf').count() === 1 && await page.locator('[data-comment]').getByText('Mentioned: Explicit teammate').count() === 1)
  await box().fill('Later feedback remains mine')
  await page.getByRole('link', { name: 'Full editor' }).click()
  await receipt('New feedback survives after prior comment acknowledgement', await box().inputValue() === 'Later feedback remains mine')
  await page.getByRole('link', { name: 'All posts', exact: true }).click()
  await page.getByRole('button', { name: 'Audit back', exact: true }).click()
  await receipt('Browser Back restores the retained feedback draft', await box().inputValue() === 'Later feedback remains mine')

  await open()
  await page.getByRole('button', { name: 'Audit saved post', exact: true }).click()
  await page.getByRole('link', { name: 'Full editor' }).click()
  await box().fill('Submitted comment for A')
  await page.getByRole('button', { name: 'Comment', exact: true }).click()
  await page.evaluate(() => window.__panel.open(302))
  await page.waitForFunction(() => document.querySelector('#route')?.textContent === '/content/write/302')
  await box().fill('Unsubmitted feedback on B')
  await page.evaluate(() => window.__finish())
  await receipt('Old post comment completion cannot clear another post feedback', await box().inputValue() === 'Unsubmitted feedback on B')
  await page.evaluate(() => window.__panel.open(301))
  await page.waitForFunction(() => document.querySelector('#route')?.textContent === '/content/write/301')
  await receipt('Original post feedback clears only its acknowledged submission', await box().inputValue() === '')
}
